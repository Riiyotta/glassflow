#!/usr/bin/env python3
"""Builds tokens/llm/token-catalog.json from the REAL token files (tokens/00-foundation/*.json,
tokens/10-semantic/semantic.json, tokens/themes/*.json). Nothing is hand-typed: every entry is
copied from those files, with the file it came from. verify_all.py rebuilds it in memory and fails
on any difference (catalog-in-sync), so the catalog cannot drift from the token files.

Usage: python3 extraction/build_token_catalog.py [--check]
"""
import json, os, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "tokens/llm/token-catalog.json")
META = {"measuredFrom", "note", "use", "kind", "class", "gap", "$type", "$description"}


def load(rel):
    with open(os.path.join(REPO, rel), encoding="utf-8") as f:
        return json.load(f)


def value_of(v):
    if not isinstance(v, dict):
        return v
    if "$value" in v:
        return v["$value"]
    rest = {k: x for k, x in v.items() if k not in META}
    return rest


def build():
    found = {}
    fdir = os.path.join(REPO, "tokens/00-foundation")
    for fn in sorted(os.listdir(fdir)):
        if not fn.endswith(".json") or fn == "motion.json":
            continue
        name = fn[:-5]
        d = load(f"tokens/00-foundation/{fn}")
        for g, kids in d.items():
            if g.startswith("$") or not isinstance(kids, dict):
                continue
            if g == "untokenised":
                continue  # raw values present in src that are NOT tokens (color.json says so)
            if all(isinstance(x, dict) for x in kids.values() if not isinstance(x, str)) and any(isinstance(x, dict) for x in kids.values()):
                grp = {k: value_of(x) for k, x in kids.items() if not k.startswith("$") and k not in META}
                found[f"{name}.{g}"] = {"source": f"tokens/00-foundation/{fn}", "tokens": grp}
            else:
                found.setdefault(name, {"source": f"tokens/00-foundation/{fn}", "tokens": {}})["tokens"][g] = value_of(kids)
    motion = load("tokens/00-foundation/motion.json")
    found["motion.patterns"] = {"source": "tokens/00-foundation/motion.json", "tokens": {k: v.get("evidence", [{}])[0].get("path", "") if isinstance(v, dict) else v for k, v in motion["patterns"].items()}}
    sem = load("tokens/10-semantic/semantic.json")
    themes = {}
    for fn in sorted(os.listdir(os.path.join(REPO, "tokens/themes"))):
        t = load(f"tokens/themes/{fn}")
        theme = t["theme"]
        colors = found[f"color.{theme}"]["tokens"]
        semantic = {}
        for k, v in sem[theme].items():
            ref = v if isinstance(v, str) else v.get("ref", v.get("$value"))
            semantic[k] = {"ref": f"color.{theme}.{ref}", "value": colors.get(ref)}
        themes[theme] = {"source": f"tokens/themes/{fn}", "family": t["family"], "default": t["default"], "semantic": semantic}
    return {
        "$description": "GENERATED by extraction/build_token_catalog.py from tokens/00-foundation, tokens/10-semantic and tokens/themes (do not hand-edit). The referenceable token names a generator may use; tokens/llm/token-policy.json says where. Values are copied for reference only: PageSpecs reference names, never values.",
        "generator": "extraction/build_token_catalog.py",
        "themes": themes,
        "groups": found,
        "counts": {"groups": len(found), "tokens": sum(len(g["tokens"]) for g in found.values()),
                   "semantic": {t: len(v["semantic"]) for t, v in themes.items()}},
    }


def render(d):
    return json.dumps(d, indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    text = render(build())
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("token-catalog in sync" if cur == text else "TOKEN-CATALOG DRIFT: rerun extraction/build_token_catalog.py")
        sys.exit(0 if cur == text else 1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    d = json.loads(text)
    print("wrote tokens/llm/token-catalog.json", d["counts"])
